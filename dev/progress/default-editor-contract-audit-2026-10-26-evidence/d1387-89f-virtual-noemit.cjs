const fs=require('fs');
const path=require('path');
const cp=require('child_process');
const repo='/home/clarence/Projects/Agents/vscode-WorkTrees/merge';
const ts=require(repo+'/node_modules/typescript');
process.chdir(repo);
const manifest=JSON.parse(fs.readFileSync('/tmp/vscode-d1387-89f-pack/manifest.json','utf8'));
if(cp.execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim()!==manifest.baseHead) throw Error('HEAD changed');
if(cp.execFileSync('git',['status','--porcelain'],{encoding:'utf8'})!=='') throw Error('source WIP');
const overlay=new Map(manifest.modules.filter(m=>m.changedSource).map(m=>[path.resolve(repo,m.sourcePath),fs.readFileSync('/tmp/vscode-d1387-89f-pack/'+m.sourcePath,'utf8')]));
const config=ts.readConfigFile(path.join(repo,'src/tsconfig.json'),ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,path.join(repo,'src'));
const options={...parsed.options,noEmit:true,skipLibCheck:true,incremental:false};
const host=ts.createCompilerHost(options);
const originalGet=host.getSourceFile.bind(host);
const originalRead=host.readFile.bind(host);
host.readFile=file=>overlay.get(path.resolve(file))??originalRead(file);
host.getSourceFile=(file,languageVersion,onError,shouldCreateNewSourceFile)=>{
 const text=overlay.get(path.resolve(file));
 return text===undefined?originalGet(file,languageVersion,onError,shouldCreateNewSourceFile):ts.createSourceFile(file,text,languageVersion,true);
};
const started=new Date().toISOString();
const program=ts.createProgram(parsed.fileNames,options,host);
const diagnostics=[...config.error?[config.error]:[],...parsed.errors,...ts.getPreEmitDiagnostics(program)];
const formatHost={getCurrentDirectory:()=>repo,getCanonicalFileName:f=>f,getNewLine:()=> '\n'};
console.log(ts.formatDiagnosticsWithColorAndContext(diagnostics,formatHost));
const result={phase:'immutable-virtual-program-noEmit-not-compile-client',baseHead:manifest.baseHead,baseSourceTree:manifest.baseSourceTree,themeRef:manifest.themeRef,overlayFiles:[...overlay.keys()],started,finished:new Date().toISOString(),diagnostics:diagnostics.map(d=>({code:d.code,category:d.category,file:d.file?.fileName,message:ts.flattenDiagnosticMessageText(d.messageText,'\n'),start:d.start})),exitCode:diagnostics.length?1:0};
fs.writeFileSync('/tmp/vscode-d1387-89f-virtual-noemit.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({diagnostics:diagnostics.length,exitCode:result.exitCode}));
process.exitCode=result.exitCode;
